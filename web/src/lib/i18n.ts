const DICTS: Record<Language, Record<MessageKey, string>> = { en, ta };

export function translate(language: Language, key: MessageKey, vars: Record<string, string | number> = {}): string {
  return DICTS[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** Hook: t('key', {vars}) in the user's chosen language. */
export function useT() {
  const language = useFloodStore((s) => s.ui.language);
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(language, key, vars);
}

